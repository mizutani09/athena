#!/usr/bin/env python3
"""Check physical consistency of NR-FLD radiative shock athdf output.

This script is intended for the Zhang et al. (2011) Section 6.6 Mach 2/5
radiative shock tests generated by nrfld_radiative_shock.cpp.  It reads the
user-output athdf file and diagnoses local thermodynamic consistency, FLD
closure consistency, steady flux conservation, and a possible T_rad bump near
the embedded hydrodynamic shock.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
from pathlib import Path
from typing import Iterable

os.environ.setdefault("MPLCONFIGDIR", "/tmp/matplotlib-codex")

import h5py
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


A_RAD = 7.5657e-15
C_LIGHT = 2.99792458e10
TINY = 1.0e-300


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Analyze NR-FLD radiative shock athdf consistency."
    )
    parser.add_argument("athdf", type=Path, help="uov_x athdf file to analyze.")
    parser.add_argument("--output-csv", type=Path, default=None, help="Optional diagnostic CSV.")
    parser.add_argument("--output-json", type=Path, default=None, help="Optional summary JSON.")
    parser.add_argument("--plot", type=Path, default=None, help="Optional diagnostic PNG.")
    parser.add_argument("--analytic", type=Path, default=None, help="Optional analytic CSV to compare.")
    parser.add_argument(
        "--align-analytic-shock",
        action="store_true",
        help="Shift analytic x so its density jump aligns with the numerical shock.",
    )
    parser.add_argument(
        "--numerical-x-shift",
        type=float,
        default=0.0,
        help="Shift numerical x coordinates before diagnostics/comparison [cm].",
    )
    parser.add_argument("--gamma", type=float, default=5.0 / 3.0)
    parser.add_argument("--a-rad", type=float, default=A_RAD)
    parser.add_argument("--c-light", type=float, default=C_LIGHT)
    parser.add_argument("--chi-r", type=float, default=0.848902, help="Rosseland opacity [cm^-1].")
    parser.add_argument("--kappa-p", type=float, default=3.92664e-5, help="Planck opacity [cm^-1].")
    parser.add_argument("--case", choices=("mach2", "mach5", "auto"), default="auto")
    parser.add_argument("--shock-x", type=float, default=None, help="Override shock position [cm].")
    parser.add_argument("--shock-window", type=float, default=None, help="Window around shock [cm].")
    parser.add_argument(
        "--shoulder-window",
        type=float,
        default=None,
        help="Window used to estimate pre/post T_rad shoulders [cm].",
    )
    parser.add_argument("--x-min", type=float, default=None, help="Limit diagnostics to x >= x-min.")
    parser.add_argument("--x-max", type=float, default=None, help="Limit diagnostics to x <= x-max.")
    parser.add_argument("--edge-cells", type=int, default=4, help="Cells excluded from robust flux spreads.")
    return parser.parse_args()


def decode_names(values: Iterable[object]) -> list[str]:
    names: list[str] = []
    for value in values:
        if isinstance(value, bytes):
            names.append(value.decode("utf-8"))
        else:
            names.append(str(value))
    return names


def variable_index(names: list[str], candidates: Iterable[str]) -> int:
    lowered = {name.lower(): i for i, name in enumerate(names)}
    for candidate in candidates:
        if candidate.lower() in lowered:
            return lowered[candidate.lower()]
    raise KeyError(f"none of {tuple(candidates)} found in {names}")


def merge_profile(x: np.ndarray, arrays: list[np.ndarray]) -> tuple[np.ndarray, list[np.ndarray]]:
    finite = np.isfinite(x)
    for arr in arrays:
        finite &= np.isfinite(arr)
    x = x[finite]
    arrays = [arr[finite] for arr in arrays]
    order = np.argsort(x)
    x = x[order]
    arrays = [arr[order] for arr in arrays]

    rounded = np.round(x, decimals=10)
    unique_x: list[float] = []
    merged = [[] for _ in arrays]
    start = 0
    while start < len(rounded):
        stop = start + 1
        while stop < len(rounded) and rounded[stop] == rounded[start]:
            stop += 1
        unique_x.append(float(np.mean(x[start:stop])))
        for n, arr in enumerate(arrays):
            merged[n].append(float(np.mean(arr[start:stop])))
        start = stop
    return np.asarray(unique_x), [np.asarray(values) for values in merged]


def load_profile(path: Path) -> dict[str, np.ndarray | float]:
    with h5py.File(path, "r") as data:
        time = float(data.attrs["Time"])
        names = decode_names(data.attrs["VariableNames"])
        values = np.asarray(data["user_out_var"], dtype=float)
        x1v = np.asarray(data["x1v"], dtype=float)

        rho = values[variable_index(names, ("rho", "density"))]
        vel = values[variable_index(names, ("vel_x", "vx", "velocity_x"))]
        pgas = values[variable_index(names, ("P_gas", "pgas", "gas_pressure"))]
        tgas = values[variable_index(names, ("T_gas", "Tgas", "gas_temperature"))]
        erad = values[variable_index(names, ("E_rad", "Erad", "radiation_energy"))]
        trad = values[variable_index(names, ("T_rad", "Trad", "radiation_temperature"))]
        prad = values[variable_index(names, ("P_rad", "Prad", "radiation_pressure"))]
        ptot = values[variable_index(names, ("P_tot", "Ptot", "total_pressure"))]
        lam = values[variable_index(names, ("lambda", "flux_limiter"))]

        x = np.broadcast_to(x1v[:, None, None, :], rho.shape).reshape(-1)
        arrays = [arr.reshape(-1) for arr in (rho, vel, pgas, tgas, erad, trad, prad, ptot, lam)]

    x, merged = merge_profile(x, arrays)
    keys = ("rho", "vel", "pgas", "tgas", "erad", "trad", "prad", "ptot", "lambda")
    out: dict[str, np.ndarray | float] = {"time": time, "x": x}
    out.update({key: arr for key, arr in zip(keys, merged)})
    return out


def relative_spread(values: np.ndarray) -> float:
    values = np.asarray(values, dtype=float)
    return float((np.nanmax(values) - np.nanmin(values)) /
                 max(0.5 * (abs(np.nanmax(values)) + abs(np.nanmin(values))), TINY))


def percentile_spread(values: np.ndarray, lo: float = 1.0, hi: float = 99.0) -> float:
    values = np.asarray(values, dtype=float)
    fmin, fmax = np.nanpercentile(values, [lo, hi])
    return float((fmax - fmin) / max(0.5 * (abs(fmax) + abs(fmin)), TINY))


def max_rel_error(a: np.ndarray, b: np.ndarray, floor: float = TINY) -> float:
    return float(np.nanmax(np.abs(a - b) / np.maximum(np.abs(b), floor)))


def detect_shock(x: np.ndarray, rho: np.ndarray) -> float:
    order = np.argsort(x)
    xs = x[order]
    rs = rho[order]
    idx = int(np.nanargmax(np.abs(np.diff(rs))))
    return float(0.5 * (xs[idx] + xs[idx + 1]))


def jump_center(x: np.ndarray, rho: np.ndarray) -> float:
    return detect_shock(np.asarray(x, dtype=float), np.asarray(rho, dtype=float))


def window_mask(x: np.ndarray, center: float, width: float) -> np.ndarray:
    return np.abs(x - center) <= 0.5 * width


def load_analytic(path: Path | None) -> dict[str, np.ndarray] | None:
    if path is None:
        return None
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        rows = list(reader)
    def col(*names: str) -> np.ndarray:
        for name in names:
            if name in reader.fieldnames:
                return np.asarray([float(row[name]) for row in rows])
        raise KeyError(f"none of {names} in analytic columns {reader.fieldnames}")
    return {
        "x": col("x_cm", "x"),
        "rho": col("rho_g_cm3", "rho"),
        "tgas": col("Tgas_K", "T_gas", "Tgas"),
        "trad": col("Trad_K", "T_rad", "Trad"),
    }


def interp_error(x: np.ndarray, y: np.ndarray, xa: np.ndarray, ya: np.ndarray) -> float:
    order = np.argsort(xa)
    xa = xa[order]
    ya = ya[order]
    mask = (x >= xa[0]) & (x <= xa[-1])
    if not np.any(mask):
        return float("nan")
    yi = np.interp(x[mask], xa, ya)
    return max_rel_error(y[mask], yi, floor=max(float(np.nanmax(np.abs(yi))) * 1.0e-12, TINY))


def analyze(profile: dict[str, np.ndarray | float], args: argparse.Namespace) -> tuple[dict, dict[str, np.ndarray]]:
    x = np.asarray(profile["x"], dtype=float) + args.numerical_x_shift
    rho = np.asarray(profile["rho"], dtype=float)
    vel = np.asarray(profile["vel"], dtype=float)
    pgas = np.asarray(profile["pgas"], dtype=float)
    tgas = np.asarray(profile["tgas"], dtype=float)
    erad = np.asarray(profile["erad"], dtype=float)
    trad = np.asarray(profile["trad"], dtype=float)
    prad = np.asarray(profile["prad"], dtype=float)
    ptot = np.asarray(profile["ptot"], dtype=float)
    lam = np.asarray(profile["lambda"], dtype=float)

    mask = np.ones_like(x, dtype=bool)
    if args.x_min is not None:
        mask &= x >= args.x_min
    if args.x_max is not None:
        mask &= x <= args.x_max
    x, rho, vel, pgas, tgas, erad, trad, prad, ptot, lam = [
        arr[mask] for arr in (x, rho, vel, pgas, tgas, erad, trad, prad, ptot, lam)
    ]

    dx = np.gradient(x)
    derdx = np.gradient(erad, x, edge_order=2)
    dtrdx = np.gradient(trad, x, edge_order=2)
    frad_diff = -args.c_light / (3.0 * args.chi_r) * derdx
    frad_adv = vel * (erad + prad)
    frad_total = frad_diff + frad_adv
    egas = pgas / (args.gamma - 1.0)
    mdot = rho * vel
    mom_flux = rho * vel * vel + pgas + prad
    gas_energy_flux = vel * (egas + 0.5 * rho * vel * vel + pgas)
    total_energy_flux = gas_energy_flux + frad_total
    rad_source = args.c_light * args.kappa_p * (args.a_rad * tgas**4 - erad)
    prad_work_proxy = prad * np.gradient(vel, x, edge_order=2)

    shock_x = args.shock_x if args.shock_x is not None else detect_shock(x, rho)
    if args.case == "mach5":
        default_shock_window = 120.0
        default_shoulder_window = 100.0
    else:
        default_shock_window = 40.0
        default_shoulder_window = 40.0
    shock_window = args.shock_window if args.shock_window is not None else default_shock_window
    shoulder_window = args.shoulder_window if args.shoulder_window is not None else default_shoulder_window

    shock_mask = window_mask(x, shock_x, shock_window)
    left_shoulder = (x >= shock_x - 2.0 * shoulder_window) & (x <= shock_x - shoulder_window)
    right_shoulder = (x >= shock_x + shoulder_window) & (x <= shock_x + 2.0 * shoulder_window)
    if np.any(shock_mask) and np.any(left_shoulder) and np.any(right_shoulder):
        trad_shock_max = float(np.nanmax(trad[shock_mask]))
        trad_shoulder = 0.5 * (float(np.nanmedian(trad[left_shoulder])) +
                               float(np.nanmedian(trad[right_shoulder])))
        trad_bump_rel = (trad_shock_max - trad_shoulder) / max(abs(trad_shoulder), TINY)
    else:
        trad_shock_max = float("nan")
        trad_shoulder = float("nan")
        trad_bump_rel = float("nan")

    analytic = load_analytic(args.analytic)
    analytic_errors = {}
    if analytic is not None:
        if args.align_analytic_shock:
            analytic = dict(analytic)
            analytic_shock_x = jump_center(analytic["x"], analytic["rho"])
            analytic["x"] = analytic["x"] + (shock_x - analytic_shock_x)
        analytic_errors = {
            "rho_max_rel": interp_error(x, rho, analytic["x"], analytic["rho"]),
            "Tgas_max_rel": interp_error(x, tgas, analytic["x"], analytic["tgas"]),
            "Trad_max_rel": interp_error(x, trad, analytic["x"], analytic["trad"]),
        }

    robust = np.ones_like(x, dtype=bool)
    if args.edge_cells > 0 and x.size > 2 * args.edge_cells:
        robust[:args.edge_cells] = False
        robust[-args.edge_cells:] = False
    robust &= ~window_mask(x, shock_x, shock_window)

    summary = {
        "file": str(args.athdf),
        "time": float(profile["time"]),
        "n_points": int(x.size),
        "x_min": float(np.nanmin(x)),
        "x_max": float(np.nanmax(x)),
        "shock_x": float(shock_x),
        "closure": {
            "max_rel_Erad_minus_aTrad4": max_rel_error(erad, args.a_rad * trad**4),
            "max_rel_Prad_minus_Erad_over_3": max_rel_error(prad, erad / 3.0),
            "max_abs_lambda_minus_1over3": float(np.nanmax(np.abs(lam - 1.0 / 3.0))),
            "max_rel_Ptot_minus_Pgas_plus_Prad": max_rel_error(ptot, pgas + prad),
        },
        "flux_residuals": {
            "mass_relative_spread": relative_spread(mdot),
            "momentum_relative_spread": relative_spread(mom_flux),
            "total_energy_relative_spread": relative_spread(total_energy_flux),
            "mass_percentile_spread_1_99": percentile_spread(mdot),
            "momentum_percentile_spread_1_99": percentile_spread(mom_flux),
            "total_energy_percentile_spread_1_99": percentile_spread(total_energy_flux),
            "mass_robust_relative_spread": relative_spread(mdot[robust]) if np.any(robust) else float("nan"),
            "momentum_robust_relative_spread": relative_spread(mom_flux[robust]) if np.any(robust) else float("nan"),
            "total_energy_robust_relative_spread": relative_spread(total_energy_flux[robust]) if np.any(robust) else float("nan"),
            "radiation_diffusive_flux_relative_spread": relative_spread(frad_diff),
        },
        "shock_region": {
            "window_cm": float(shock_window),
            "Trad_shock_max_K": trad_shock_max,
            "Trad_shoulder_K": trad_shoulder,
            "Trad_bump_relative": float(trad_bump_rel),
            "max_abs_dTrad_dx_K_per_cm": float(np.nanmax(np.abs(dtrdx[shock_mask])))
            if np.any(shock_mask) else float("nan"),
            "max_abs_rad_source": float(np.nanmax(np.abs(rad_source[shock_mask])))
            if np.any(shock_mask) else float("nan"),
            "max_abs_Prad_divu_proxy": float(np.nanmax(np.abs(prad_work_proxy[shock_mask])))
            if np.any(shock_mask) else float("nan"),
        },
        "analytic_errors": analytic_errors,
    }

    diagnostics = {
        "x": x,
        "rho": rho,
        "vel": vel,
        "pgas": pgas,
        "tgas": tgas,
        "erad": erad,
        "trad": trad,
        "prad": prad,
        "lambda": lam,
        "dEr_dx": derdx,
        "Fdiff": frad_diff,
        "Frad_adv": frad_adv,
        "Frad_total": frad_total,
        "mdot": mdot,
        "mom_flux": mom_flux,
        "gas_energy_flux": gas_energy_flux,
        "total_energy_flux": total_energy_flux,
        "rad_source": rad_source,
        "Prad_divu_proxy": prad_work_proxy,
    }
    return summary, diagnostics


def write_diagnostics_csv(path: Path, diagnostics: dict[str, np.ndarray]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    keys = list(diagnostics)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(keys)
        for values in zip(*(diagnostics[key] for key in keys)):
            writer.writerow(values)


def make_plot(path: Path, summary: dict, diagnostics: dict[str, np.ndarray]) -> None:
    x = diagnostics["x"]
    fig, axes = plt.subplots(4, 1, figsize=(9.0, 10.5), sharex=True, constrained_layout=True)
    axes[0].plot(x, diagnostics["rho"], color="tab:blue", lw=1.4, label=r"$\rho$")
    axes[0].set_ylabel(r"$\rho$")
    axes[0].ticklabel_format(axis="y", style="sci", scilimits=(0, 0))
    axes[0].legend(frameon=False)

    axes[1].plot(x, diagnostics["tgas"], color="tab:orange", lw=1.2, label=r"$T_\mathrm{gas}$")
    axes[1].plot(x, diagnostics["trad"], color="tab:green", lw=1.2, label=r"$T_\mathrm{rad}$")
    axes[1].set_ylabel("T [K]")
    axes[1].legend(frameon=False)

    axes[2].plot(x, diagnostics["mdot"] / np.nanmedian(diagnostics["mdot"]) - 1.0,
                 label="mass", lw=1.1)
    axes[2].plot(x, diagnostics["mom_flux"] / np.nanmedian(diagnostics["mom_flux"]) - 1.0,
                 label="momentum", lw=1.1)
    axes[2].plot(x, diagnostics["total_energy_flux"] /
                 np.nanmedian(diagnostics["total_energy_flux"]) - 1.0,
                 label="total energy", lw=1.1)
    axes[2].set_ylabel("flux / median - 1")
    axes[2].legend(frameon=False, ncol=3)

    axes[3].plot(x, diagnostics["Fdiff"], lw=1.1, label=r"$F_\mathrm{diff}$")
    axes[3].plot(x, diagnostics["rad_source"], lw=1.1, label=r"$c\kappa_P(aT_g^4-E_r)$")
    axes[3].plot(x, diagnostics["Prad_divu_proxy"], lw=1.1, label=r"$P_r\,du/dx$")
    axes[3].set_ylabel("local terms")
    axes[3].set_xlabel("x [cm]")
    axes[3].legend(frameon=False)

    for ax in axes:
        ax.axvline(summary["shock_x"], color="0.35", ls=":", lw=1.0)
        ax.grid(alpha=0.25)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=180)
    plt.close(fig)


def print_summary(summary: dict) -> None:
    print(json.dumps(summary, indent=2, sort_keys=True))


def main() -> None:
    args = parse_args()
    profile = load_profile(args.athdf)
    summary, diagnostics = analyze(profile, args)
    print_summary(summary)

    if args.output_csv is not None:
        write_diagnostics_csv(args.output_csv, diagnostics)
        print(f"wrote diagnostics CSV: {args.output_csv}")
    if args.output_json is not None:
        args.output_json.parent.mkdir(parents=True, exist_ok=True)
        args.output_json.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
        print(f"wrote summary JSON: {args.output_json}")
    if args.plot is not None:
        make_plot(args.plot, summary, diagnostics)
        print(f"wrote plot: {args.plot}")


if __name__ == "__main__":
    main()
